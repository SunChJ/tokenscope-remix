export const TEXT: Record<Locale, Copy> = { en, zh };

const I18nContext = createContext({ locale: "en" as Locale, text: en as Copy });

export function I18nProvider({ locale, children }: { locale: Locale; children: ReactNode }) {
  return <I18nContext.Provider value={{ locale, text: TEXT[locale] }}>{children}</I18nContext.Provider>;
}

export function useI18n() {
  return useContext(I18nContext);
}

export const localeTag = (locale: Locale) => locale === "zh" ? "zh-CN" : "en-US";

const weekdays: Record<string, string> = {
  Mon: "周一", Tue: "周二", Wed: "周三", Thu: "周四", Fri: "周五", Sat: "周六", Sun: "周日",
};
const months: Record<string, number> = {
  Jan: 1, Feb: 2, Mar: 3, Apr: 4, May: 5, Jun: 6,
  Jul: 7, Aug: 8, Sep: 9, Oct: 10, Nov: 11, Dec: 12,
};

export function localizeSeriesText(value: string, locale: Locale) {
  if (locale === "en" || !value) return value;
  return value.split(" – ").map((part) => {
    const weekdayDate = part.match(/^(Mon|Tue|Wed|Thu|Fri|Sat|Sun) (Jan|Feb|Mar|Apr|May|Jun|Jul|Aug|Sep|Oct|Nov|Dec) (\d{1,2})$/);
    if (weekdayDate) return `${months[weekdayDate[2]]}月${weekdayDate[3]}日 ${weekdays[weekdayDate[1]]}`;
    const fullDate = part.match(/^(Jan|Feb|Mar|Apr|May|Jun|Jul|Aug|Sep|Oct|Nov|Dec) (\d{1,2}), (\d{4})( \d{2}:\d{2})?$/);
    if (fullDate) return `${fullDate[3]}年${months[fullDate[1]]}月${fullDate[2]}日${fullDate[4] ?? ""}`;
    const monthDate = part.match(/^(Jan|Feb|Mar|Apr|May|Jun|Jul|Aug|Sep|Oct|Nov|Dec) (\d{1,2})$/);
    if (monthDate) return `${months[monthDate[1]]}月${monthDate[2]}日`;
    return weekdays[part] ?? part;
  }).join(" – ");
}
